// RegressionSuite represents a portable specification of a recorded trajectory for CI/CD runs.
type RegressionSuite struct {
	Version      string            `json:"version"`
	TrajectoryID string            `json:"trajectory_id"`
	AgentID      string            `json:"agent_id"`
	Model        string            `json:"model"`
	TotalSteps   int               `json:"total_steps"`
	ExpectedHash string            `json:"expected_final_hash"`
	Steps        []ExecutableStep  `json:"steps"`
	Metadata     map[string]any    `json:"metadata,omitempty"`
}

// ExecutableStep represents a single step assertion in the regression suite.
type ExecutableStep struct {
	Index           int                 `json:"index"`
	Type            string              `json:"type"`
	Prompt          string              `json:"prompt"`
	ExpectedOutput  string              `json:"expected_output"`
	StateHash       string              `json:"state_hash"`
	ExpectedTools   []models.ToolCall   `json:"expected_tools,omitempty"`
	MemoryVariables json.RawMessage     `json:"memory_variables,omitempty"`
}

// ExportJSON generates a portable JSON regression test suite.
func ExportJSON(t *models.Trajectory) ([]byte, error) {
	suite := RegressionSuite{
		Version:      "v1",
		TrajectoryID: t.ID,
		AgentID:      t.AgentID,
		Model:        t.Model,
		TotalSteps:   len(t.Steps),
		Metadata:     t.Metadata,
	}

	if len(t.Steps) > 0 {
		suite.ExpectedHash = t.Steps[len(t.Steps)-1].StateHash
	}

	for _, s := range t.Steps {
		var memVars json.RawMessage
		if s.MemorySnapshot != nil {
			memVars = s.MemorySnapshot.Variables
		}
		suite.Steps = append(suite.Steps, ExecutableStep{
			Index:           s.StepIndex,
			Type:            string(s.StepType),
			Prompt:          s.Prompt,
			ExpectedOutput:  s.Response,
			StateHash:       s.StateHash,
			ExpectedTools:   s.ToolCalls,
			MemoryVariables: memVars,
		})
	}

	return json.MarshalIndent(suite, "", "  ")
}

// ExportGoTest generates a standalone, self-contained Go test file that executes assertions without external dependencies.
func ExportGoTest(t *models.Trajectory) (string, error) {
	const tmpl = `// Code generated by TraceReplay (https://github.com/alexandrmotologa/tracereplay). DO NOT EDIT.
package regression_test

import (
	"encoding/json"
	"testing"
)

func TestTrajectory_{{ .CleanID }}(t *testing.T) {
	expectedSteps := {{ .StepsCount }}
	trajectoryID := "{{ .TrajectoryID }}"
	agentID := "{{ .AgentID }}"

	t.Logf("Running regression test for trajectory %s (agent: %s)", trajectoryID, agentID)

	steps := []struct {
		Index     int
		Prompt    string
		Response  string
		StateHash string
		ToolCount int
	}{
{{- range .Steps }}
		{
			Index:     {{ .StepIndex }},
			Prompt:    {{ printf "%q" .Prompt }},
			Response:  {{ printf "%q" .Response }},
			StateHash: {{ printf "%q" .StateHash }},
			ToolCount: {{ len .ToolCalls }},
		},
{{- end }}
	}

	if len(steps) != expectedSteps {
		t.Fatalf("expected %d steps, got %d", expectedSteps, len(steps))
	}

	for _, s := range steps {
		t.Run(string(rune('A'+s.Index)), func(t *testing.T) {
			if s.StateHash == "" {
				t.Errorf("step %d missing expected state hash", s.Index)
			}
			t.Logf("Step %d verified with state hash %s", s.Index, s.StateHash)
		})
	}
}
`
	cleanID := strings.ReplaceAll(t.ID, "-", "_")
	data := struct {
		CleanID      string
		TrajectoryID string
		AgentID      string
		StepsCount   int
		Steps        []models.Step
	}{
		CleanID:      cleanID,
		TrajectoryID: t.ID,
		AgentID:      t.AgentID,
		StepsCount:   len(t.Steps),
		Steps:        t.Steps,
	}

	funcMap := template.FuncMap{
		"quote": func(s string) string {
			return fmt.Sprintf("%q", s)
		},
	}

	parsed, err := template.New("gotest").Funcs(funcMap).Parse(tmpl)
	if err != nil {
		return "", err
	}

	var buf bytes.Buffer
	if err := parsed.Execute(&buf, data); err != nil {
		return "", err
	}

	return buf.String(), nil
}

// ExportPythonTest generates a standalone pytest suite reproducing the agent trajectory.
func ExportPythonTest(t *models.Trajectory) (string, error) {
	const tmpl = `# Auto-generated by TraceReplay (https://github.com/alexandrmotologa/tracereplay)
import pytest
import json

TRAJECTORY_ID = "{{ .TrajectoryID }}"
AGENT_ID = "{{ .AgentID }}"
EXPECTED_STEPS = {{ .StepsCount }}

RECORDED_STEPS = [
{{- range .Steps }}
    {
        "index": {{ .StepIndex }},
        "prompt": {{ printf "%q" .Prompt }},
        "response": {{ printf "%q" .Response }},
        "state_hash": {{ printf "%q" .StateHash }},
        "status": "{{ .Status }}",
        "tool_count": {{ len .ToolCalls }},
    },
{{- end }}
]

def test_trajectory_regression_steps_count():
    assert len(RECORDED_STEPS) == EXPECTED_STEPS

@pytest.mark.parametrize("step", RECORDED_STEPS, ids=lambda s: f"step_{s['index']}")
def test_trajectory_step_determinism(step):
    assert step["state_hash"] != "", f"Step {step['index']} has empty state hash"
    assert step["status"] in ["success", "failed"]
`
	data := struct {
		TrajectoryID string
		AgentID      string
		StepsCount   int
		Steps        []models.Step
	}{
		TrajectoryID: t.ID,
		AgentID:      t.AgentID,
		StepsCount:   len(t.Steps),
		Steps:        t.Steps,
	}

	parsed, err := template.New("pytest").Parse(tmpl)
	if err != nil {
		return "", err
	}

	var buf bytes.Buffer
	if err := parsed.Execute(&buf, data); err != nil {
		return "", err
	}

	return buf.String(), nil
}
